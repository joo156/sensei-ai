function chunk(id: string, page: number, section: string, text: string, tags: string[]): WsChunk {
  return { id, page, tokens: 380 + ((page * 37) % 180), text, tags, section };
}

function q(
  id: string,
  prompt: string,
  options: string[],
  answer: string,
  rationale: string,
  doc: string,
  page: number,
  chunkId: string,
  snippet: string,
  review: ReviewState = "Pending",
): GeneratedQuestion {
  return {
    id,
    prompt,
    type: "MCQ",
    difficulty: "Intermediate",
    options,
    answer,
    rationale,
    bloom: "Understanding",
    quality: 9.2,
    grounded: 100,
    estMinutes: 2,
    review,
    citations: [{ doc, page, chunk: chunkId, snippet, score: 0.92 }],
  };
}

